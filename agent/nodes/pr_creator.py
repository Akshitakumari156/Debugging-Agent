"""
agent/nodes/pr_creator.py — PR Creator Node

Responsibilities:
  1. Create a feature branch in the repo
  2. Copy modified files from sandbox → temp dir → GitHub API
  3. Commit them to the branch
  4. Open a Pull Request with full description
"""

from __future__ import annotations

import logging
import re
import uuid
from datetime import datetime

from agent.state import AgentState
from backend.config import settings
from db.database import db_session
from db.models import Task, TaskLog, LogLevel, TaskStatus
from gh_integration.pr_manager import PRManager
from sandbox.executor import SandboxExecutor
from backend.ws_manager import ws_manager

logger = logging.getLogger(__name__)

PR_DESCRIPTION_TEMPLATE = """## 🤖 AutoDebug — Automated Fix

**Issue:** #{issue_id} — {issue_title}

---

### 🐛 Problem

{issue_body}

---

### 🔍 Root Cause

{root_cause}

---

### 🔧 Fix Applied

{fix_plan}

**Files Modified:**
{files_list}

---

### ✅ Validation

- Tests passed: **{tests_passed}**
- Tests failed: **{tests_failed}**
- All original tests passing: **Yes**

---

### 🧠 Agent Reasoning

{llm_reasoning}

---

*This PR was automatically generated by [AutoDebug](https://github.com/your-org/autodebug) — an autonomous debugging agent.*
*Task ID: `{task_id}` | Generated at: {timestamp}*
"""


async def pr_creator_node(state: AgentState) -> AgentState:
    """
    PR Creator Node.
    
    Creates a git branch, commits all modified files from the sandbox,
    and opens a Pull Request with a detailed description.
    """
    task_id = state["task_id"]
    logger.info(f"[PRCreator] Starting for task {task_id}")

    async with db_session() as db:
        task_uuid = uuid.UUID(task_id)
        task = await db.get(Task, task_uuid)
        task.status = TaskStatus.PR_CREATING
        task.current_node = "pr_creator"
        await db.commit()

        try:
            executor  = SandboxExecutor(state["container_id"])
            workspace = state["workspace_path"]

            # -----------------------------------------------------------------
            # 1. Create branch name
            # -----------------------------------------------------------------
            # Use task_id for uniqueness, and issue_id for context
            issue_ref   = state.get("issue_id") or "no-issue"
            slug        = _slugify(state.get("issue_title", "fix"))[:30]
            # Format: autodebug/t-abcd1234-i-2-fix-title
            branch_name = f"autodebug/t-{task_id[:8]}-i-{issue_ref}-{slug}"

            await _log(db, task_id, "pr_creator", LogLevel.INFO,
                       f"Creating branch: {branch_name}")

            # Create branch in sandbox
            await executor.run(
                f"cd {workspace} && "
                f"git config user.email '{settings.GITHUB_BOT_EMAIL}' && "
                f"git config user.name '{settings.GITHUB_BOT_NAME}' && "
                f"git checkout -b {branch_name}"
            )

            # -----------------------------------------------------------------
            # 2. Stage + commit changes
            # -----------------------------------------------------------------
            files_modified = state.get("files_modified", [])
            for fpath in files_modified:
                await executor.run(f"cd {workspace} && git add {fpath}")

            issue_title = state.get("issue_title", "fix")
            issue_id    = state.get("issue_id")
            commit_msg  = f"fix: resolve issue #{issue_id if issue_id else 'N/A'} — {issue_title[:60]}\n\nAutomated fix by AutoDebug agent."
            commit_result = await executor.run(
                f"cd {workspace} && git commit -m '{commit_msg}'"
            )

            if commit_result.exit_code != 0:
                raise RuntimeError(f"git commit failed: {commit_result.output}")

            # Extract commit SHA
            sha_result = await executor.run(f"cd {workspace} && git rev-parse HEAD")
            commit_sha = sha_result.output.strip()

            # -----------------------------------------------------------------
            # 3. Push branch via HTTPS with token
            # -----------------------------------------------------------------
            # Inject token into remote URL for authentication
            # Use the clone_url from state if available (might be the fork)
            # Inject token into remote URL for authentication
            # Use the clone_url from state if available (might be the fork)
            # Ensure we have the correct push URL by checking fork status directly 
            # This makes the node robust against state loss
            repo_url   = state["repo_url"]
            pr_manager = PRManager(settings.GITHUB_TOKEN)
            fork_info = await pr_manager.fork_repo(repo_url)
            push_url = fork_info["clone_url"]
            is_forked = fork_info["is_forked"]
            fork_owner = fork_info.get("owner_login")

            token      = settings.GITHUB_TOKEN
            auth_url   = push_url.replace("https://", f"https://{token}@")

            # Use --force to ensure we can overwrite existing branches on retry
            push_result = await executor.run(
                f"cd {workspace} && git push {auth_url} {branch_name} --force 2>&1"
            )

            if push_result.exit_code != 0:
                raise RuntimeError(f"git push failed: {push_result.output}")

            await _log(db, task_id, "pr_creator", LogLevel.INFO,
                       f"Pushed branch {branch_name} to {push_url}")

            # -----------------------------------------------------------------
            # 4. Open PR via GitHub API
            # -----------------------------------------------------------------
            # If forked, head must be "username:branch"
            pr_head = branch_name
            if is_forked and fork_owner:
                pr_head = f"{fork_owner}:{branch_name}"

            pr_body = PR_DESCRIPTION_TEMPLATE.format(
                issue_id=issue_id,
                issue_title=state.get("issue_title", ""),
                issue_body=state.get("issue_body", "")[:500],
                root_cause=state.get("root_cause", ""),
                fix_plan=state.get("fix_plan", ""),
                files_list="\n".join(f"- `{f}`" for f in files_modified),
                tests_passed=state.get("tests_passed", 0),
                tests_failed=state.get("tests_failed", 0),
                llm_reasoning=state.get("llm_reasoning", "")[:500],
                task_id=task_id,
                timestamp=datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"),
            )

            pr_manager = PRManager(settings.GITHUB_TOKEN)
            pr = await pr_manager.create_pr(
                repo_url=repo_url,
                title=f"[AutoDebug] Fix: {issue_title[:72]}",
                body=pr_body,
                head=pr_head,
                base="main",
                issue_number=issue_id if isinstance(issue_id, int) else None,
            )

            pr_url    = pr.html_url
            pr_number = pr.number

            await _log(db, task_id, "pr_creator", LogLevel.INFO,
                       f"PR created: {pr_url}")

            # -----------------------------------------------------------------
            # 5. Persist results
            # -----------------------------------------------------------------
            task.status      = TaskStatus.COMPLETED
            task.pr_url      = pr_url
            task.pr_number   = pr_number
            task.branch_name = branch_name
            from datetime import timezone
            task.completed_at = datetime.now(timezone.utc)
            await db.commit()

            return {
                **state,
                "branch_name":  branch_name,
                "commit_sha":   commit_sha,
                "pr_url":       pr_url,
                "pr_number":    pr_number,
                "pr_description": pr_body,
                "is_done":      True,
            }

        except Exception as exc:
            logger.exception(f"[PRCreator] Failed: {exc}")
            await _log(db, task_id, "pr_creator", LogLevel.ERROR, str(exc))
            return {**state, "error": f"PRCreator failed: {exc}"}


def _slugify(text: str) -> str:
    """Convert text to URL-safe slug."""
    text = text.lower().strip()
    text = re.sub(r"[^\w\s-]", "", text)
    text = re.sub(r"[\s_-]+", "-", text)
    return text.strip("-")


async def _log(db, task_id, node, level, message, log_metadata=None):
    db.add(TaskLog(task_id=task_id, level=level, node=node,
                   message=message, log_metadata=log_metadata))
    await db.commit()
    await ws_manager.send_log(str(task_id), level.value, node, message, log_metadata)
